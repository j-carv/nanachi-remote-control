import { z } from 'zod';

/** Persisted opt-in selection in <NANACHI_HOME>/mcp.json. Missing settings enable no agents. */
export const NanachiMcpSettingsSchema = z.object({
  enabledAgents: z.array(z.string().min(1)).default([]),
});

export const NanachiMcpAgentSchema = z.object({
  id: z.string().min(1),
  label: z.string().min(1),
  enabled: z.boolean(),
});

export type NanachiMcpAgent = z.infer<typeof NanachiMcpAgentSchema>;

/** GET /api/mcp/agents and PUT /api/mcp/agents/:id (paired-device authentication). */
export const NanachiMcpResponseSchema = z.object({
  agents: z.array(NanachiMcpAgentSchema),
});

export type NanachiMcpResponse = z.infer<typeof NanachiMcpResponseSchema>;

/** Changes one agent's selection without overwriting the choices for other agents. */
export const SetNanachiMcpAgentRequestSchema = z.object({ enabled: z.boolean() });

/** MCP phone_send accepts a file or a screenshot, never caller-supplied session credentials. */
export const PhoneSendToolInputSchema = z.object({
  path: z.string().min(1).optional().describe('File to send, absolute or relative to the session workspace. Omit when taking a screenshot.'),
  screenshot: z.literal(true).optional().describe('Capture all PC monitors (Windows only). Omit when sending a file.'),
  caption: z.string().optional().describe('Optional caption shown with the delivered file.'),
}).strict().refine((input) => (input.path !== undefined) !== (input.screenshot === true), {
  message: 'Provide exactly one of path or screenshot: true',
});

/** An unanswered decision expires; no deadline or cancellation can select an option. */
export const ASK_USER_TIMEOUT_MS = 5 * 60_000;

export const AskUserOptionSchema = z.object({
  id: z.string().regex(/^[A-Za-z0-9_-]{1,64}$/),
  label: z.string().trim().min(1).max(200),
}).strict();

export type AskUserOption = z.infer<typeof AskUserOptionSchema>;

export const AskUserInputSchema = z.object({
  question: z.string().trim().min(1).max(2000),
  options: z.array(AskUserOptionSchema).min(2).max(8),
}).strict().superRefine((input, context) => {
  const ids = new Set<string>();
  for (const [index, option] of input.options.entries()) {
    if (ids.has(option.id)) {
      context.addIssue({ code: 'custom', path: ['options', index, 'id'], message: 'Option IDs must be unique' });
    }
    ids.add(option.id);
  }
});

export type AskUserInput = z.infer<typeof AskUserInputSchema>;

/** Internal transport identity, generated by the MCP process rather than supplied by the model. */
export const AskUserRequestSchema = AskUserInputSchema.safeExtend({ requestId: z.uuid() });
export type AskUserRequest = z.infer<typeof AskUserRequestSchema>;

export const AskUserResultSchema = z.discriminatedUnion('status', [
  z.object({ status: z.literal('answered'), option: AskUserOptionSchema }).strict(),
  z.object({
    status: z.literal('cancelled'),
    reason: z.enum(['user_cancelled', 'expired', 'disconnected', 'session_ended']),
  }).strict(),
]);

export type AskUserResult = z.infer<typeof AskUserResultSchema>;

/** A paired device chooses one of the stored options, or explicitly cancels with null. */
export const RespondUserQuestionRequestSchema = z.object({
  optionId: AskUserOptionSchema.shape.id.nullable(),
}).strict();
